/** One pill that answers "do I need to look at this bot?" — worse of the latest run row and the heartbeat. */
export function BotPill({ bot, run = null }: { bot: Bot; run?: Run | null }) {
  const h = botHealth(bot, run);
  return <span className={`pill ${h.cls}`}>{h.label}</span>;
}

/** DRY RUN vs LIVE, unmistakable. */
export function ModePill({ run, big = false }: { run: Run | null; big?: boolean }) {
  if (!run) return null;
  return run.mode === "execute"
    ? <span className={`mode live${big ? " big" : ""}`}><Abbr term="LIVE">LIVE</Abbr></span>
    : <span className={`mode dry${big ? " big" : ""}`}><Abbr term="DRY RUN">DRY RUN</Abbr></span>;
}

export const SimTag = () => <span className="simtag" title="Generated by DEMO_MODE's seeded simulator, not real trading">SIMULATED</span>;
export const BtTag = () => <span className="bttag">BACKTEST · HYPOTHETICAL</span>;

/** Bloomberg-style panel: dark title bar, numbered for "2 <GO>", function code chip on the right. */
export function Panel({ n, title, code, meta, children, className = "", hot = false, sim = false, bt = false, id }: {
  n?: number; title: React.ReactNode; code?: string; meta?: React.ReactNode; children: React.ReactNode; className?: string;
  hot?: boolean; sim?: boolean; bt?: boolean; id?: string;
}) {
  return (
    <section className={`panel${hot ? " hot" : ""}${bt ? " bt" : ""} ${className}`} id={id ?? (n !== undefined ? `p${n}` : undefined)} data-panel={n}>
      <div className="panel-head">
        <h2>{n !== undefined && <span className="pn">{n})</span>} {title}</h2>
        {sim && <SimTag />}
        {bt && <BtTag />}
        {meta && <span className="meta">{meta}</span>}
        {code && <span className="code">{code}</span>}
      </div>
      <div className="panel-body">{children}</div>
    </section>
  );
}

export type SoftKey = { n: number; label: string; href: string; ext?: boolean };

/** Function-header row: fn badge, white title, one-line description, red soft keys. */
export function PageHead({ fn, title, desc, right, keys = [] }: { fn: string; title: string; desc?: React.ReactNode; right?: React.ReactNode; keys?: SoftKey[] }) {
  return (
    <div className="fnhead">
      <span className="fn">{fn}</span>
      <h1>{title}</h1>
      {desc && <p>{desc}</p>}
      <div className="right">
        {right}
        {keys.map((k) => k.ext
          ? <a key={k.n} className="softkey" href={k.href} target="_blank" rel="noreferrer">{k.n}) {k.label}</a>
          : <Link key={k.n} className="softkey" href={k.href}>{k.n}) {k.label}</Link>)}
      </div>
    </div>
  );
}

/** Glossary term with a tooltip; focusable, so a tap on mobile opens it. */
export function Abbr({ term, children }: { term: string; children?: React.ReactNode }) {
  const def = GLOSSARY[term];
  if (!def) return <>{children ?? term}</>;
  return (
    <span className="abbr" tabIndex={0} aria-label={`${term}: ${def}`}>
      {children ?? term}
      <span className="abbr-pop" role="tooltip">{def}</span>
    </span>
  );
}

/** Signed value with sign discipline: +/−, zero dim. */
export function Sgn({ v, kind = "usd", digits, className = "" }: { v: number | null | undefined; kind?: "usd" | "pct"; digits?: number; className?: string }) {
  if (v === null || v === undefined || Number.isNaN(v)) return <span className={`zero ${className}`}>—</span>;
  const cls = v > 0 ? "pos" : v < 0 ? "neg" : "zero";
  return <span className={`${cls} ${className}`}>{kind === "usd" ? usd(v, true, digits ?? 2) : pct(v, digits ?? 1, true)}</span>;
}

/** Heat-colored score cell. */
export function ScoreCell({ score }: { score: number }) {
  const a = Math.max(0, Math.min(1, (score - 30) / 70)) * 0.35;
  return <td className="num score" style={{ background: `rgba(255,160,40,${a.toFixed(3)})` }}><b>{score.toFixed(1)}</b></td>;
}

export function FlagTags({ flags }: { flags: string[] | null }) {
  if (!flags?.length) return null;
  return (
    <span className="flags">
      {flags.map((f) => { const i = flagInfo(f); return <span key={f} className={`tag ${i.tone}`} title={`${i.label}: ${i.help}`}>{i.code}</span>; })}
    </span>
  );
}

export function FlagLegend() {
  return (
    <div className="flaglegend">
      <span className="muted">FLAGS</span>
      {Object.entries(FLAGS).map(([k, i]) => (
        <span key={k} title={i.help}><span className={`tag ${i.tone}`}>{i.code}</span> {i.label}</span>
      ))}
    </div>
  );
}

export function TodayBanner({ t }: { t: Today }) {
  return (
    <div className={`today ${t.tone}`} role="status">
      <b className="t-head">{t.head}</b>
      <span className="t-state">{t.state}</span>
      {t.parts.map((p) => <span key={p} className="t-part">{p}</span>)}
      {t.countdownTo && <span className="t-part">{t.countdownLabel} <b><Countdown to={t.countdownTo} /></b></span>}
      <span className="t-pl">
        DAY <Num v={t.dayPl}><Sgn v={t.dayPl} /></Num> <span className="muted">(</span><Sgn v={t.dayPct} kind="pct" digits={2} /><span className="muted">)</span>
      </span>
      {t.rerun && <code className="t-rerun" title="Re-run from the bot machine">RERUN: {t.rerun}</code>}
    </div>
  );
}

export function Timeline({ steps }: { steps: Step[] }) {
  return (
    <ol className="timeline" aria-label="Today's schedule">
      {steps.map((s, i) => (
        <li key={s.key} className={s.state}>
          <span className="tl-dot" aria-hidden="true">{s.state === "done" ? "✓" : s.state === "failed" ? "✕" : s.state === "late" ? "!" : s.state === "skipped" ? "–" : i + 1}</span>
          <span className="tl-l">{s.label} <b>{s.at}</b></span>
          <span className="tl-s">{s.state === "done" ? `DONE ${s.actual ?? ""}` : s.state === "skipped" ? "SKIPPED" : s.state === "late" ? "LATE" : s.state === "failed" ? "FAILED" : "PENDING"}</span>
        </li>
      ))}
    </ol>
  );
}

export function AlertBanner({ alerts }: { alerts: Alert[] }) {
  if (!alerts.length) return null;
  return (
    <div className="alertbar" role="alert">
      {alerts.map((a, i) => (
        <span key={i} className={a.level}>
          <b>{a.level === "bad" ? "ALERT" : "WARN"}</b> {a.href ? <Link href={a.href}>{a.text}</Link> : a.text}
        </span>
      ))}
    </div>
  );
}

